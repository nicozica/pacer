/* Skip Workout entry points on the home screen: the "Skip workout…" link beside the Next workout
 * panel (it navigates to /skip/) and the list of already-skipped workouts. All data comes from
 * existing endpoints; nothing here approves, syncs or publishes. */
(function skipWorkoutUi() {
  'use strict';

  const { esc, request, plannedDuration, stamp, recoveryHtml, copy } = window.PacerSkipCommon;
  const fmt = () => window.PacerWorkoutFormat;
  const openIds = new Set();
  const byId = (id) => document.getElementById(id);
  const api = (id, suffix) => `/api/workouts/${encodeURIComponent(id)}/${suffix}`;
  const pageUrl = (id) => `/skip/?id=${encodeURIComponent(id)}`;

  /* ---------- skipped workouts list ---------- */

  function conflictHtml(record) {
    return `<p class="skip-conflict" role="alert">Conflict: activity ${esc(record.completedAfterSkipActivityId)} was completed for this workout after it was skipped. `
      + 'Pacer has not changed either record.</p>';
  }

  function cardHtml(record) {
    const workout = record.workout;
    const id = workout.pacerWorkoutId;
    const conflict = record.outcomeStatus === 'completed_after_skip';
    const open = openIds.has(id) ? ' open' : '';
    const badge = conflict
      ? '<span class="status-badge is-conflict">Skipped · activity found</span>'
      : '<span class="status-badge is-skipped">Skipped</span>';
    return `<article class="skipped-workout${conflict ? ' has-conflict' : ''}" data-id="${esc(id)}">`
      + `<div class="skipped-head"><div class="skipped-title">${esc(workout.title || 'Untitled workout')} ${badge}</div>`
      + `<div class="skipped-meta">${esc(fmt().formatDateLabel(workout.schedule?.localDate))} · ${esc(workout.workoutType || '')} · ${esc(plannedDuration(workout))}</div></div>`
      + (conflict ? conflictHtml(record) : '')
      + `<div class="actions skipped-actions"><a class="skip-link" href="${pageUrl(id)}">Open skip page</a><button type="button" class="button-primary" data-skip-action="copy">Copy Skip Training Brief</button>`
      + '<span class="skip-copy-status field-help" role="status" aria-live="polite"></span></div>'
      + `<details data-skip-details${open}><summary>Details, recovery snapshot and brief</summary>`
      + `<div class="skip-detail-body"><h5>Workout (original, unchanged)</h5>${fmt().renderWorkout(workout, { omitTitle: true })}`
      + `<h5>Explanation</h5><p>${record.skip.explanation ? esc(record.skip.explanation) : '<em>None given.</em>'}</p>`
      + `<h5>Recovery snapshot <small>taken when skipped, ${esc(stamp(record.skip.skippedAt))}</small></h5>${recoveryHtml(record.skip.wellnessSnapshot)}`
      + '<h5>Skip Training Brief <small>generated by Pacer for Coachat</small></h5>'
      + '<textarea class="skip-brief" rows="10" readonly aria-label="Skip Training Brief" placeholder="Loading brief…"></textarea>'
      + '<p class="skip-note">Paste the brief into Coachat, then paste its standalone future-workout JSON into step 2 above and choose Import Workout.</p>'
      + '</div></details></article>';
  }

  function render() {
    const host = byId('skipped-workouts');
    if (!host) return;
    const records = (window.PacerWorkouts?.records() ?? [])
      .filter((record) => record.skip)
      .sort((a, b) => String(b.workout.schedule?.localDate).localeCompare(String(a.workout.schedule?.localDate)));
    host.classList.toggle('hidden', records.length === 0);
    host.innerHTML = records.length
      ? `<h4>Skipped workouts</h4>${records.map(cardHtml).join('')}`
      : '';
    host.querySelectorAll('details[open]').forEach((el) => loadBriefInto(el.closest('[data-id]')));
  }

  async function fetchBrief(id) {
    const details = await request(api(id, 'skip'));
    if (!details.brief) throw new Error('The backend returned no brief for this workout.');
    return details.brief;
  }

  async function loadBriefInto(card) {
    if (!card) return;
    const area = card.querySelector('.skip-brief');
    const id = card.dataset.id;
    try {
      const brief = await fetchBrief(id);
      briefs.set(id, brief);
      area.value = brief;
    } catch (err) {
      area.value = '';
      area.placeholder = `Could not load the brief: ${err.message}`;
    }
  }

  async function copyBrief(card) {
    const status = card.querySelector('.skip-copy-status');
    const button = card.querySelector('[data-skip-action="copy"]');
    button.disabled = true;
    status.textContent = 'Preparing brief…';
    try {
      const brief = await fetchBrief(card.dataset.id); // always current (planning anchor may change)
      briefs.set(card.dataset.id, brief);
      const area = card.querySelector('.skip-brief');
      if (area) area.value = brief;
      const ok = await copy(brief);
      status.textContent = ok ? '✓ Copied. Paste it into Coachat.' : 'Copy failed. Open the details and copy the brief manually.';
    } catch (err) {
      status.textContent = `Could not load the brief: ${err.message}`;
    } finally {
      button.disabled = false;
      setTimeout(() => { status.textContent = ''; }, 4000);
    }
  }

  /* ---------- skip action beside the target workout ---------- */

  /** Skip link for stored, approved, unskipped, not-syncing workouts. */
  function renderTargetAction(target) {
    const host = byId('workout-skip-actions');
    if (!host) return;
    const record = target?.record;
    const lifecycle = record?.workout?.lifecycle;
    const live = Boolean(record) && !record.skip && lifecycle?.approvalStatus === 'approved' && !target.superseded;
    const eligible = live && lifecycle.syncStatus !== 'syncing';
    host.classList.toggle('hidden', !eligible);
    if (!eligible) { host.innerHTML = ''; return; }
    const wid = record.workout.pacerWorkoutId;
    host.innerHTML = `<a class="skip-link" data-skip-action="open" href="${pageUrl(wid)}">Skip workout…</a>`;
  }

  document.addEventListener('click', (event) => {
    const button = event.target.closest('[data-skip-action="copy"]');
    if (button) copyBrief(button.closest('[data-id]'));
  });
  document.addEventListener('toggle', (event) => {
    const details = event.target;
    if (!details.matches?.('[data-skip-details]')) return;
    const card = details.closest('[data-id]');
    if (details.open) { openIds.add(card.dataset.id); loadBriefInto(card); } else openIds.delete(card.dataset.id);
  }, true);

  window.PacerWorkouts?.onChange(render);
  window.PacerSkip = { render, renderTargetAction };
  if (window.PacerWorkouts?.isLoaded()) render();
}());
